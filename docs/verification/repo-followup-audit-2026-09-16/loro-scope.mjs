import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const source=process.argv[2];
const root=fs.mkdtempSync(path.join(os.tmpdir(),'loro-scope-audit-'));
fs.mkdirSync(path.join(root,'ceo/records'),{recursive:true});
fs.mkdirSync(path.join(root,'companies'));
const cli=path.join(source,'richos/engine/loro/bin/loro-write.mjs');
const invoke=(args)=>spawnSync(process.execPath,[cli,...args,'--corpus',root,'--json'],{encoding:'utf8'});
const append=invoke(['append','--id','secret','--kind','fact','--body','Synthetic confidential acquisition budget is 42 million.']);
if(append.status!==0)throw Error(append.stderr);
const direct=invoke(['correct','--ref','rec:ceo/records/secret','--scope','org-shared','--why','Synthetic correction']);
const replaced=invoke(['supersede','--ref','rec:ceo/records/secret','--id','replacement','--kind','fact','--scope','org-shared','--body','Synthetic confidential acquisition budget is 43 million.','--why','Synthetic correction']);
const {compileContext}=await import(path.join(source,'richos/engine/loro/lib/compile.js'));
const slice=compileContext({corpusRoot:root,topic:'confidential acquisition budget',audience:'worker',budgetChars:4000});
assert.equal(direct.status,5);assert.equal(replaced.status,0);assert.ok(slice.items.some(r=>r.ref==='rec:ceo/records/replacement' && r.scope==='org-shared'));
console.log(JSON.stringify({directCorrectionExit:direct.status,directCorrectionError:direct.stderr.trim(),supersedeExit:replaced.status,supersedeError:replaced.stderr.trim(),workerItems:slice.items},null,2));
fs.rmSync(root,{recursive:true,force:true});
