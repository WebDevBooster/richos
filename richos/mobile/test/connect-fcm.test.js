test('FCM retries follow the APNs job semantics: bounded attempts, backoff and one-hour expiry', async t => {
  const s = await service(t);
  await s.call('PUT', '/v1/push/device', s.android);
  for (let n = 0; n < 10; n++) s.g.state.answers.push(fcmError(503, 'UNAVAILABLE'));
  await s.call('POST', '/v1/push/events', s.event);
  // The shared backoff is 2, 4, 8, then 15 minutes: attempts at minutes 0, 5, 10, 20 and 35 on a
  // five-minute scheduler, and never a sixth.
  const sent = [];
  for (let n = 0; n < 11; n++) { s.advance(300000); await s.reconcile(); sent.push(s.g.state.sends.length); }
  assert.deepEqual(sent, [2, 3, 3, 4, 4, 4, 5, 5, 5, 5, 5], 'backoff schedule and at most five attempts');
  assert.equal((await s.jobs())[0].state, 'failed');
  s.advance(3600000); await s.reconcile();
  assert.equal((await s.jobs()).length, 0, 'jobs expire after one hour');
  // A pending job that reaches its expiry is deleted, never sent.
  s.g.state.answers.length = 0; s.g.state.answers.push(fcmError(503, 'UNAVAILABLE'));
  await s.call('POST', '/v1/push/events', { ...s.event, eventRef: 'e'.repeat(64) });
  const before = s.g.state.sends.length;
  s.advance(3600001); await s.reconcile();
  assert.equal(s.g.state.sends.length, before); assert.equal((await s.jobs()).length, 0);
});

test('replacing an iPhone with an Android phone, and back, moves delivery and drops the old queue', async t => {
  const s = await service(t);
  await s.call('PUT', '/v1/push/device', s.iphone);
  s.apnsOutcome('retry'); await s.call('POST', '/v1/push/events', s.event);
  assert.equal(s.apnsCalls.length, 1); assert.equal((await s.jobs()).length, 1);
  assert.equal((await s.call('PUT', '/v1/push/device', { ...s.android, revision: 2 })).status, 200);
  assert.equal((await s.jobs()).length, 0, 'the iPhone\'s pending job cannot reach the new phone');
  s.advance(300000); await s.reconcile(); assert.equal(s.apnsCalls.length, 1);
  assert.equal((await s.call('POST', '/v1/push/events', { ...s.event, revision: 2 })).status, 202);
  assert.equal(s.g.state.sends.length, 1); assert.equal(s.apnsCalls.length, 1);
  // Same revision, same Android registration: idempotent. Same revision, anything else: conflict.
  assert.equal((await s.call('PUT', '/v1/push/device', { ...s.android, revision: 2 })).status, 200);
  assert.equal((await s.call('PUT', '/v1/push/device', { ...s.iphone, revision: 2 })).status, 409);
  assert.equal((await s.call('PUT', '/v1/push/device', { ...s.android, revision: 2, token: 'y'.repeat(160) })).status, 409);
  // Reverse transition.
  s.apnsOutcome('sent');
  assert.equal((await s.call('PUT', '/v1/push/device', { ...s.iphone, revision: 3 })).status, 200);
  const row = await s.row(); assert.equal(row.platform, 'apns'); assert.equal(row.environment, 'sandbox');
  await s.call('POST', '/v1/push/events', { ...s.event, eventRef: 'f'.repeat(64), revision: 3 });
  assert.equal(s.apnsCalls.length, 2); assert.equal(s.g.state.sends.length, 1);
  // Revocation clears the platform with the token.
  assert.equal((await s.call('PUT', '/v1/push/device', { revision: 4, generation: 1, deviceHash: null, token: null, route: 'tailnet' })).status, 200);
  const revoked = await s.row(); assert.equal(revoked.token, null); assert.equal(revoked.platform, null);
});

test('schema 3 migrates a live schema-2 database in place; the deployed schema-2 Worker keeps working meanwhile', async t => {
  const schema = readFileSync(join(__dirname, '../service/connect/schema.sql'), 'utf8');
  const [migration] = schema.split('\n').filter(line => line.startsWith('-- migrate 3: ')).map(line => line.slice('-- migrate 3: '.length));
  assert.match(migration, /^ALTER TABLE push_bindings ADD COLUMN platform TEXT/);
  const schema2 = schema.replace(/,\n  platform TEXT CHECK \(platform IS NULL OR platform IN \('apns','fcm'\)\)\n\);/, '\n);');
  assert.notEqual(schema2, schema, 'the schema-2 shape is derived by removing exactly the new column');
  const columns = db => db.prepare('PRAGMA table_info(push_bindings)').all().map(({ name, type, notnull }) => [name, type, notnull]);
  const old = new DatabaseSync(':memory:'), fresh = new DatabaseSync(':memory:'); t.after(() => { old.close(); fresh.close(); });
  old.exec(schema2); fresh.exec(schema);
  // A binding written by the deployed schema-2 Worker, with exactly its statement.
  const schema2Insert = 'INSERT INTO push_bindings(host_id,revision,device_hash,token,environment,topic,route,generation,updated_at) VALUES(?,?,?,?,?,?,?,?,?)';
  old.prepare(schema2Insert).run('a'.repeat(32), 1, 'a'.repeat(64), 'd'.repeat(64), 'sandbox', 'dev.richos.mobile.integration', 'tailnet', 1, 1);
  old.exec(migration);
  assert.deepEqual(columns(old), columns(fresh), 'the migrated table has exactly the fresh schema-3 shape');
  const row = old.prepare('SELECT * FROM push_bindings').get();
  assert.equal(row.platform, null); assert.equal(row.token, 'd'.repeat(64));
  // Between migration and upload the schema-2 Worker still writes; afterwards bad values are refused.
  old.prepare(schema2Insert).run('b'.repeat(32), 1, null, null, null, null, 'tailnet', 1, 1);
  assert.throws(() => old.prepare("UPDATE push_bindings SET platform='gcm'").run(), /CHECK constraint/);
  assert.throws(() => old.exec(migration), /duplicate column/, 'a second run refuses loudly instead of changing anything');
  const { platformOf } = await import('../service/connect/notifications.mjs');
  assert.equal(platformOf(row), 'apns', 'a pre-migration row is APNs to the schema-3 code');
});

