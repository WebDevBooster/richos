test('the managed artifact uploads connect/fcm.mjs, resolves every import and carries FCM identifiers only', async () => {
  const { managedArtifact } = await import('../cli/connect.mjs');
  const profile = { accountId: 'a'.repeat(32), zoneId: 'b'.repeat(32), databaseId: crypto.randomUUID(), domain: 'example.com', capacity: 10,
    fcm: { projectId: PROJECT, apps: [APP] } };
  const artifact = managedArtifact(profile), names = artifact.modules.map(module => module.name);
  assert(names.includes('connect/fcm.mjs'));
  for (const module of artifact.modules) {
    for (const [, specifier] of module.source.matchAll(/^import\s+(?:[^'"]*from\s+)?['"](\.[^'"]+)['"]/gm)) {
      assert(names.includes(new URL(specifier, 'file:///' + module.name).pathname.slice(1)), `${module.name} imports ${specifier}`);
    }
  }
  const bindings = Object.fromEntries(artifact.metadata.bindings.map(row => [row.name, row]));
  assert.deepEqual(bindings.FCM_PROJECT_ID, { name: 'FCM_PROJECT_ID', type: 'plain_text', text: PROJECT });
  assert.deepEqual(bindings.FCM_APPS, { name: 'FCM_APPS', type: 'plain_text', text: APP });
  assert.equal(bindings.FCM_SERVICE_ACCOUNT, undefined, 'the key is a preserved secret, never part of the upload');
  assert.deepEqual(artifact.metadata.keep_bindings, ['secret_text']);
  const without = managedArtifact({ ...profile, fcm: undefined });
  assert(!without.metadata.bindings.some(row => row.name.startsWith('FCM_')), 'no FCM profile, no FCM bindings');
  for (const fcm of [{ projectId: 'X' }, { projectId: PROJECT }, { projectId: PROJECT, apps: [] }, { projectId: PROJECT, apps: ['not-an-id'] },
    { projectId: PROJECT, apps: [APP], serviceAccount: '{}' }, { apps: [APP] }]) {
    assert.throws(() => managedArtifact({ ...profile, fcm }), /FCM/, JSON.stringify(fcm));
  }
});
