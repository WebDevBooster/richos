// PEM armor is assembled at run time: every key here is generated by the test and discarded.
const pem = (label, bytes) => { const dashes = '-'.repeat(5);
  return `${dashes}BEGIN ${label}${dashes}\n${Buffer.from(bytes).toString('base64').match(/.{1,64}/g).join('\n')}\n${dashes}END ${label}${dashes}\n`; };

// A real RSA service-account key, a fake Google that verifies every assertion with its public half,
// and a scripted answer queue for the send endpoint.
async function google({ now }) {
  const keys = await crypto.subtle.generateKey({ name: 'RSASSA-PKCS1-v1_5', modulusLength: 2048, publicExponent: new Uint8Array([1, 0, 1]), hash: 'SHA-256' }, true, ['sign', 'verify']);
  const privateKey = pem('PRIVATE KEY', await crypto.subtle.exportKey('pkcs8', keys.privateKey));
  const serviceAccount = JSON.stringify({ type: 'service_account', project_id: PROJECT, private_key_id: 'f'.repeat(40), private_key: privateKey,
    client_email: `push@${PROJECT}.iam.gserviceaccount.com`, client_id: '1'.repeat(21), token_uri: 'https://oauth2.googleapis.com/token' });
  const state = { oauth: [], sends: [], answers: [], oauthAnswers: [], issued: 0, requests: [] };
  async function fetchImpl(url, options) {
    state.requests.push({ url, options });
    assert.equal(options.redirect, 'manual'); assert(options.signal instanceof AbortSignal);
    if (url === 'https://oauth2.googleapis.com/token') {
      const form = new URLSearchParams(options.body);
      assert.equal(options.method, 'POST'); assert.equal(options.headers['content-type'], 'application/x-www-form-urlencoded');
      assert.equal(form.get('grant_type'), 'urn:ietf:params:oauth:grant-type:jwt-bearer');
      const [header, claims, signature] = form.get('assertion').split('.');
      assert(await crypto.subtle.verify('RSASSA-PKCS1-v1_5', keys.publicKey, Buffer.from(signature, 'base64url'), Buffer.from(header + '.' + claims)), 'assertion is signed by the service-account key');
      state.oauth.push({ header: JSON.parse(Buffer.from(header, 'base64url')), claims: JSON.parse(Buffer.from(claims, 'base64url')) });
      const answer = state.oauthAnswers.shift();
      if (answer instanceof Error) throw answer;
      if (answer) return answer;
      return Response.json({ access_token: `ya29.fixture-${++state.issued}`, expires_in: 3599, token_type: 'Bearer' });
    }
    assert.equal(url, `https://fcm.googleapis.com/v1/projects/${PROJECT}/messages:send`);
    state.sends.push({ authorization: options.headers.authorization, body: JSON.parse(options.body) });
    const answer = state.answers.shift();
    if (answer instanceof Error) throw answer;
    return answer || Response.json({ name: `projects/${PROJECT}/messages/0:1` });
  }
  const env = { FCM_SERVICE_ACCOUNT: serviceAccount, FCM_PROJECT_ID: PROJECT, FCM_APPS: APP };
  return { keys, privateKey, serviceAccount, env, state, fetchImpl };
}
const fcmError = (status, errorCode, extra = []) => Response.json({ error: { code: status, status: 'X',
  details: [{ '@type': 'type.googleapis.com/google.firebase.fcm.v1.FcmError', errorCode }, ...extra] } }, { status });
const binding = { host_id: 'a'.repeat(32), token: 'fixture-token_' + 'x'.repeat(140) + ':APA91b', topic: APP, platform: 'fcm' };
const job = (at, extra = {}) => ({ event_ref: 'b'.repeat(64), thread_ref: 'c'.repeat(64), expires_at: at + 3600000, ...extra });

test('FCM signs an RS256 service-account assertion, caches the access token and sends a data-only high-priority message', async () => {
  const { FCM } = await import('../service/connect/fcm.mjs');
  let time = 1790000000000; const g = await google({ now: () => time });
  const fcm = new FCM(g.env, { fetchImpl: g.fetchImpl, now: () => time });
  const preview = JSON.stringify({ v: 1, nonce: 'a'.repeat(16), body: 'b'.repeat(100) });
  assert.deepEqual(await fcm.send(binding, job(time, { preview })), { outcome: 'sent' });
  const [{ header, claims }] = g.state.oauth;
  assert.deepEqual(header, { alg: 'RS256', typ: 'JWT', kid: 'f'.repeat(40) });
  assert.deepEqual(claims, { iss: `push@${PROJECT}.iam.gserviceaccount.com`, scope: 'https://www.googleapis.com/auth/firebase.messaging',
    aud: 'https://oauth2.googleapis.com/token', iat: 1790000000, exp: 1790003600 });
  const [send] = g.state.sends;
  assert.equal(send.authorization, 'Bearer ya29.fixture-1');
  assert.deepEqual(send.body, { message: { token: binding.token,
    data: { v: '1', host: binding.host_id, thread: 'c'.repeat(64), event: 'b'.repeat(64), preview },
    android: { priority: 'HIGH', ttl: '3600s', collapse_key: 'b'.repeat(64), restricted_package_name: APP } } });
  assert(!('notification' in send.body.message) && !('notification' in send.body.message.android), 'no visible text crosses Google');
  assert(Object.values(send.body.message.data).every(value => typeof value === 'string'), 'FCM data values are strings');
  // The access token is reused until five minutes before expiry, then a fresh assertion is signed.
  time += 3000 * 1000; await fcm.send(binding, job(time));
  assert.equal(g.state.oauth.length, 1); assert.equal(g.state.sends[1].authorization, 'Bearer ya29.fixture-1');
  assert.equal(g.state.sends[1].body.message.data.preview, undefined, 'no preview field without ciphertext');
  // The Worker builds a sender per request; the token outlives the instance.
  await new FCM(g.env, { fetchImpl: g.fetchImpl, now: () => time }).send(binding, job(time));
  assert.equal(g.state.oauth.length, 1, 'a new sender for the same secret reuses the access token');
  time += 400 * 1000; await fcm.send(binding, job(time - 3590 * 1000));
  assert.equal(g.state.oauth.length, 2); assert.equal(g.state.sends[3].authorization, 'Bearer ya29.fixture-2');
  assert.equal(g.state.sends[3].body.message.android.ttl, '10s', 'the TTL is the job\'s remaining lifetime');
  // No key material in any request.
  const keyLine = g.privateKey.split('\n')[1];
  for (const request of g.state.requests) assert(!String(request.options.body).includes(keyLine));
});

test('FCM maps Google\'s answers onto the APNs outcomes: invalid, retry and configuration', async () => {
  const { FCM } = await import('../service/connect/fcm.mjs');
  const time = 1790000000000, g = await google({ now: () => time });
  const fcm = new FCM(g.env, { fetchImpl: g.fetchImpl, now: () => time });
  const badToken = { '@type': 'type.googleapis.com/google.rpc.BadRequest', fieldViolations: [{ field: 'message.token', description: 'Invalid registration token' }] };
  const cases = [
    [fcmError(404, 'UNREGISTERED'), { outcome: 'invalid' }],
    [fcmError(403, 'SENDER_ID_MISMATCH'), { outcome: 'invalid' }],
    [fcmError(400, 'INVALID_ARGUMENT', [badToken]), { outcome: 'invalid' }],
    // A bad request that does not name the token is our fault: the phone keeps its registration.
    [fcmError(400, 'INVALID_ARGUMENT', [{ '@type': 'type.googleapis.com/google.rpc.BadRequest', fieldViolations: [{ field: 'message.data' }] }]), { outcome: 'configuration', code: 'http_400' }],
    [fcmError(403, 'PERMISSION_DENIED'), { outcome: 'configuration', code: 'http_403' }],
    [fcmError(429, 'QUOTA_EXCEEDED'), { outcome: 'retry', code: 'http_429' }],
    [fcmError(503, 'UNAVAILABLE'), { outcome: 'retry', code: 'http_503' }],
    [fcmError(500, 'INTERNAL'), { outcome: 'retry', code: 'http_500' }],
    [new Response('not json', { status: 502 }), { outcome: 'retry', code: 'http_502' }],
    [Object.assign(Error('timed out'), { name: 'TimeoutError' }), { outcome: 'retry', code: 'timeout' }],
    [new TypeError('network'), { outcome: 'retry', code: 'transport' }],
  ];
  for (const [answer, expected] of cases) { g.state.answers.push(answer); assert.deepEqual(await fcm.send(binding, job(time)), expected, JSON.stringify(expected)); }
  // A rejected access token is dropped, so the next attempt signs a new assertion.
  const before = g.state.oauth.length;
  g.state.answers.push(fcmError(401, 'UNAUTHENTICATED'));
  assert.deepEqual(await fcm.send(binding, job(time)), { outcome: 'retry', code: 'http_401' });
  await fcm.send(binding, job(time)); assert.equal(g.state.oauth.length, before + 1);
});

