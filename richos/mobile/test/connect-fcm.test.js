// The real signed handler, real SQLite schema, real FCM class against the fake Google, and a
// recording APNs sender: every job must go to exactly one provider, the registration's.
async function service(t, { route = 'tailnet' } = {}) {
  const f = await fixture(t), { handle, reconcile } = await import('../service/connect-worker.mjs'), { FCM } = await import('../service/connect/fcm.mjs');
  const g = await google({ now: () => f.store.now() });
  Object.assign(f.env, g.env, { APNS_TEAM_ID: 'A123456789', APNS_SANDBOX_KEY_ID: 'B123456789', APNS_SANDBOX_KEY: 'server-secret', APNS_TOPICS: 'dev.richos.mobile.integration' });
  const apnsCalls = []; let apnsOutcome = 'sent';
  const ports = { store: f.store, provider: f.provider, now: () => f.store.now(),
    apns: { send: async (b, j) => { apnsCalls.push({ binding: b, job: j }); return { outcome: apnsOutcome }; } },
    fcm: new FCM(f.env, { fetchImpl: g.fetchImpl, now: () => f.store.now() }) };
  const id = await f.identity();
  const call = (method, path, data) => id.request(method, path, data === undefined ? '' : JSON.stringify(data)).then(request => handle(request, f.env, ports));
  assert.equal((await call('POST', route === 'connect' ? '/v1/hosts' : '/v1/push/hosts')).status, 200);
  const deviceHash = 'a'.repeat(64);
  if (route === 'connect') assert.equal((await call('PUT', '/v1/host/device', { generation: 1, deviceKeyHash: deviceHash })).status, 200);
  const android = { revision: 1, generation: 1, deviceHash, token: binding.token, platform: 'fcm', topic: APP, route };
  const iphone = { revision: 1, generation: 1, deviceHash, token: 'd'.repeat(64), topic: 'dev.richos.mobile.integration', environment: 'sandbox', route };
  const event = { eventRef: 'b'.repeat(64), threadRef: 'c'.repeat(64), revision: 1, deviceHash };
  const row = () => f.store.statement('SELECT * FROM push_bindings WHERE host_id=?', id.id).first();
  const jobs = async () => (await f.store.statement('SELECT * FROM push_jobs WHERE host_id=?', id.id).all()).results;
  return { ...f, g, id, call, android, iphone, event, row, jobs, apnsCalls, apnsOutcome: value => { apnsOutcome = value; }, reconcile: () => reconcile(f.env, ports) };
}

